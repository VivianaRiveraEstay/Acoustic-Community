function dY = vivi(~,Y,P)
%% Parametros del modelo:
r(1)= P(1);
r(2)= P(2);
r(3)= P(3);
r(4)= P(4)
K(1)= P(5); 
K(2)= P(6); 
K(3)= P(7)
K(4)= P(8)
a(1,2)= P(9); 
a(1,3)= P(10);
a(1,4)= P(11); 
a(2,1)= P(12);
a(2,3)= P(13);
a(2,4)= P(14);
a(3,1)= P(15);
a(3,2)= P(16);
a(3,4)= P(17);
a(4,1)= P(18);
a(4,2)= P(19);
a(4,3)= P(20);
b12= P(21);
b13= P(22);
b14= P(23);
b21= P(24);
b23= P(25);
b24= P(26);
b31= P(27);
b32= P(28);
b34= P(29);
b41= P(30);
b42= P(31);
b43= P(32);
G1= P(33); 
G2= P(34);
G3= P(35);
G4= P(36);

%El modelo
%% Lista de Ecuaciones
dY=zeros(8,1);
%
dY(1) = r(1)*(1-(Y(1)/K(1)))*Y(1)-a(1,2)*exp(-((Y(5)-Y(6))^(2))/2*b12^2)*Y(1)*Y(2)-a(1,3)*exp(-((Y(5)-Y(7))^(2))/2*b13^2)*Y(1)*Y(3)-a(1,4)*exp(-((Y(5)-Y(8))^(2))/2*b14^2)*Y(1)*Y(4);
dY(2) = r(2)*(1-(Y(2)/K(2)))*Y(2)-a(2,1)*exp(-((Y(6)-Y(5))^(2))/2*b21^2)*Y(2)*Y(1)-a(2,3)*exp(-((Y(6)-Y(7))^(2))/2*b23^2)*Y(2)*Y(3)-a(2,4)*exp(-((Y(5)-Y(8))^(2))/2*b13^2)*Y(2)*Y(4);
dY(3) = r(3)*(1-(Y(3)/K(3)))*Y(3)-a(3,1)*exp(-((Y(7)-Y(5))^(2))/2*b31^2)*Y(3)*Y(1)-a(3,2)*exp(-((Y(7)-Y(6))^(2))/2*b32^2)*Y(3)*Y(2)-a(3,4)*exp(-((Y(7)-Y(8))^(2))/2*b34^2)*Y(3)*Y(4);
dY(4) = r(4)*(1-(Y(4)/K(4)))*Y(4)-a(4,1)*exp(-((Y(8)-Y(5))^(2))/2*b41^2)*Y(4)*Y(1)-a(4,2)*exp(-((Y(8)-Y(6))^(2))/2*b42^2)*Y(4)*Y(2)-a(4,3)*exp(-((Y(8)-Y(7))^(2))/2*b43^2)*Y(4)*Y(3);
dY(5) = (Y(5)-2)*(0-Y(5))*G1*(Y(2)*a(1,2)*exp(-((Y(5)-Y(6))^(2))/2*b12^2)*((Y(5)-Y(6))/b12^2)+Y(3)*a(1,3)*exp(-((Y(5)-Y(7))^(2))/2*b13^2)*((Y(5)-Y(7))/b13^2)+Y(4)*a(1,4)*exp(-((Y(5)-Y(8))^(2))/2*b14^2)*((Y(5)-Y(8))/b14^2));
dY(6) = (Y(6)-2)*(0-Y(6))*G2*(Y(1)*a(2,1)*exp(-((Y(6)-Y(5))^(2))/2*b21^2)*((Y(6)-Y(5))/b21^2)+Y(3)*a(2,3)*exp(-((Y(6)-Y(7))^(2))/2*b23^2)*((Y(6)-Y(7))/b23^2)+Y(4)*a(2,4)*exp(-((Y(6)-Y(8))^(2))/2*b24^2)*((Y(6)-Y(8))/b24^2));
dY(7) = (Y(7)-2)*(0-Y(7))*G3*(Y(1)*a(3,1)*exp(-((Y(7)-Y(5))^(2))/2*b31^2)*((Y(7)-Y(5))/b21^2)+Y(2)*a(3,2)*exp(-((Y(7)-Y(6))^(2))/2*b32^2)*((Y(7)-Y(6))/b32^2)+Y(4)*a(3,4)*exp(-((Y(7)-Y(8))^(2))/2*b34^2)*((Y(7)-Y(8))/b34^2));
dY(8) = (Y(8)-2)*(0-Y(8))*G4*(Y(1)*a(4,1)*exp(-((Y(8)-Y(5))^(2))/2*b41^2)*((Y(8)-Y(5))/b41^2)+Y(3)*a(4,2)*exp(-((Y(8)-Y(6))^(2))/2*b42^2)*((Y(8)-Y(6))/b42^2)+Y(3)*a(4,3)*exp(-((Y(8)-Y(7))^(2))/2*b43^2)*((Y(8)-Y(7))/b43^2));

end
